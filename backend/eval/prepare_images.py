"""Build the Tier 2 image benchmark manifest from Wikimedia Commons.

    python eval/prepare_images.py --per-generator 8 --real 40

Writes `eval/images_ood.json`: an out-of-distribution set of AI-generated images grouped
BY GENERATOR, plus real photographs for the negative class. Checked in so results are
reproducible; re-run only to refresh it.

Why Commons: stable URLs, permissive licensing, and — unusually — it categorises
AI-generated images by the software that made them, which is what makes a per-generator
breakdown possible. `Organika/sdxl-detector` is SDXL-specialised, so one aggregate number
would hide most of what is worth knowing about it.

Why thumbnail URLs rather than originals: the production fetch path downscales to a 512px
max edge before inference (see app/services/image_fetch.py), so evaluating on 512px
renditions measures what the deployed system actually sees. Benchmarking pristine
originals would overstate accuracy, because resampling destroys exactly the
high-frequency generator artifacts these detectors key on.
"""
from __future__ import annotations

import argparse
import json
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from app.services.image_fetch import SSL_CONTEXT  # noqa: E402 — needs the path above

API = "https://commons.wikimedia.org/w/api.php"
# Commons rejects requests without a descriptive agent (HTTP 400).
UA = "Dasfax-WS4-eval/0.1 (student project; Tier 2 screening benchmark)"
THUMB_WIDTH = 512

# Generator categories, mapped to the short label used in the report.
GENERATORS = {
    "Images generated by Midjourney": "midjourney",
    "Images generated by Stable Diffusion": "stable-diffusion",
    "Images generated by DALL-E": "dall-e",
    "Images generated by Flux (text-to-image model)": "flux",
    "Images generated by Grok": "grok",
    "Images generated by Gemini": "gemini",
    "Images generated by Imagen": "imagen",
    "Images generated by Ideogram": "ideogram",
    "Images generated by Adobe Firefly AI": "firefly",
    "Images generated by thispersondoesnotexist.com": "stylegan",
}
# Real photographs. "Quality images" are ordinary competent photography rather than the
# heavily-composited pictures that dominate Featured Pictures, which makes them a fairer
# negative class for news imagery.
REAL_CATEGORIES = {
    "Quality images of people": "photo-people",
    "Quality images of places": "photo-places",
    "Quality images of objects": "photo-objects",
    "Quality images of vehicles": "photo-vehicles",
}

_IMAGE_SUFFIXES = (".jpg", ".jpeg", ".png", ".webp")


def _get(params: dict, *, attempts: int = 4) -> dict:
    """One API call, with backoff. Commons rate-limits an unauthenticated client after a
    handful of rapid requests, which surfaces as HTTP 429 and looks exactly like a wrong
    category name if the code swallows the status."""
    url = f"{API}?{urllib.parse.urlencode({**params, 'format': 'json'})}"
    request = urllib.request.Request(url, headers={"User-Agent": UA})
    for attempt in range(attempts):
        try:
            with urllib.request.urlopen(  # noqa: S310 — fixed https host
                request, timeout=30, context=SSL_CONTEXT
            ) as response:
                return json.loads(response.read())
        except urllib.error.HTTPError as exc:
            if exc.code in (429, 503) and attempt < attempts - 1:
                time.sleep(2 ** attempt)
                continue
            raise RuntimeError(f"HTTP {exc.code} for {params.get('cmtitle') or params.get('titles')}") from exc
    raise RuntimeError("exhausted retries")


def category_files(category: str, limit: int) -> list[str]:
    """File titles in a category, walking one level of subcategories if needed."""
    titles: list[str] = []
    data = _get({
        "action": "query", "list": "categorymembers", "cmtitle": f"Category:{category}",
        "cmtype": "file", "cmlimit": min(500, limit * 6),
    })
    titles += [m["title"] for m in data.get("query", {}).get("categorymembers", [])]

    if len(titles) < limit:
        subs = _get({
            "action": "query", "list": "categorymembers", "cmtitle": f"Category:{category}",
            "cmtype": "subcat", "cmlimit": 10,
        })
        for sub in subs.get("query", {}).get("categorymembers", []):
            if len(titles) >= limit * 4:
                break
            more = _get({
                "action": "query", "list": "categorymembers", "cmtitle": sub["title"],
                "cmtype": "file", "cmlimit": 100,
            })
            titles += [m["title"] for m in more.get("query", {}).get("categorymembers", [])]
            time.sleep(0.1)

    return [t for t in titles if t.lower().endswith(_IMAGE_SUFFIXES)]


def thumbnail_urls(titles: list[str]) -> list[tuple[str, str]]:
    """Map file titles to (title, thumbnail url), 40 at a time."""
    out: list[tuple[str, str]] = []
    for start in range(0, len(titles), 40):
        batch = titles[start:start + 40]
        data = _get({
            "action": "query", "titles": "|".join(batch), "prop": "imageinfo",
            "iiprop": "url", "iiurlwidth": THUMB_WIDTH,
        })
        for page in data.get("query", {}).get("pages", {}).values():
            info = (page.get("imageinfo") or [{}])[0]
            url = info.get("thumburl") or info.get("url")
            if url:
                out.append((page["title"], url))
        time.sleep(0.1)
    return out


def collect(categories: dict[str, str], label: str, per_category: int) -> list[dict]:
    samples: list[dict] = []
    for category, tag in categories.items():
        try:
            titles = category_files(category, per_category)
        except Exception as exc:
            print(f"  {tag:<18} SKIPPED ({exc})")
            continue
        if not titles:
            print(f"  {tag:<18} no files found")
            continue
        pairs = thumbnail_urls(titles[: per_category * 2])[:per_category]
        for title, url in pairs:
            samples.append({
                "id": f"{tag}-{len(samples):03d}",
                "label": label,
                "generator": tag,
                "source_title": title,
                "image_url": url,
            })
        print(f"  {tag:<18} {len(pairs):>3} images")
        time.sleep(0.5)  # stay under the unauthenticated rate limit
    return samples


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build the WS4 image benchmark manifest.")
    parser.add_argument("--per-generator", type=int, default=8)
    parser.add_argument("--real", type=int, default=40, help="Total real photographs.")
    parser.add_argument("--out", type=Path, default=Path(__file__).parent / "images_ood.json")
    args = parser.parse_args(argv)

    print("Collecting AI-generated images by generator:")
    synthetic = collect(GENERATORS, "synthetic", args.per_generator)
    print("\nCollecting real photographs:")
    real = collect(REAL_CATEGORIES, "authentic", max(1, args.real // len(REAL_CATEGORIES)))

    manifest = {
        "meta": {
            "name": "dasfax-ws4-images-ood-v1",
            "source": "Wikimedia Commons",
            "purpose": "Out-of-distribution accuracy for the Tier 2 AI-generated-image detector.",
            "rendition": f"{THUMB_WIDTH}px thumbnails — matches what the production fetch path sees",
            "caveat": (
                "Commons AI categories contain a lot of illustration and digital art, not only "
                "photorealistic imagery. Read the per-generator table with that in mind: the "
                "deployment case that matters is a photorealistic fake in a news article."
            ),
            "counts": {"synthetic": len(synthetic), "authentic": len(real)},
        },
        "samples": synthetic + real,
    }
    args.out.write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    print(f"\nwrote {args.out}  ({len(synthetic)} synthetic, {len(real)} authentic)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
